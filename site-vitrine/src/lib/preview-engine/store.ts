// Memory (development and tests only)

type MemoryRow = PreviewRow & { idempotency_key: string; token_hash: string; lease_id: string | null; lease_until: number };

export class MemoryPreviewStore implements PreviewStore {
  readonly kind = "memory" as const;
  private rows = new Map<string, MemoryRow>();

  private clone(row: MemoryRow): PreviewRow {
    // Mirrors the JSON round trip of the real store: callers never share references.
    const { idempotency_key: _k, token_hash: _t, lease_id: _l, lease_until: _u, ...rest } = row;
    void _k;
    void _t;
    void _l;
    void _u;
    return JSON.parse(JSON.stringify(rest)) as PreviewRow;
  }

  async create(input: CreatePreview) {
    for (const row of this.rows.values()) if (row.idempotency_key === input.idempotencyKey) return this.clone(row);
    const now = new Date().toISOString();
    const row: MemoryRow = {
      id: input.id,
      status: "running",
      stage: input.stage,
      needs: null,
      company_name: input.companyName,
      siren: null,
      official_domain: null,
      fingerprint: null,
      input: input.input,
      attribution: input.attribution,
      pipeline: input.pipeline,
      work: input.work,
      company_profile: null,
      audit_report: null,
      preview_blueprint: null,
      email: null,
      notified_at: null,
      lead_id: null,
      engine_version: input.engineVersion,
      error_code: null,
      created_at: now,
      updated_at: now,
      ready_at: null,
      expires_at: new Date(Date.now() + 30 * 86_400_000).toISOString(),
      idempotency_key: input.idempotencyKey,
      token_hash: input.tokenHash,
      lease_id: null,
      lease_until: 0,
    };
    this.rows.set(row.id, JSON.parse(JSON.stringify(row)));
    return this.clone(row);
  }

  async get(id: string) {
    const row = this.rows.get(id);
    return row ? this.clone(row) : null;
  }

  async claim(id: string, leaseMs: number) {
    const row = this.rows.get(id);
    if (!row) return null;
    if (row.lease_until > Date.now()) return { row: this.clone(row), leaseId: null };
    row.lease_id = randomUUID();
    row.lease_until = Date.now() + leaseMs;
    return { row: this.clone(row), leaseId: row.lease_id };
  }

  async save(id: string, leaseId: string, patch: PreviewPatch) {
    const row = this.rows.get(id);
    if (!row || row.lease_id !== leaseId) return false;
    Object.assign(row, JSON.parse(JSON.stringify(patch)), { updated_at: new Date().toISOString(), lease_id: null, lease_until: 0 });
    return true;
  }

  async findByFingerprint(fingerprint: string, statuses: PreviewStatus[], maxAgeHours: number, excludeId?: string) {
    const since = Date.now() - maxAgeHours * 3_600_000;
    const match = [...this.rows.values()]
      .filter((r) => r.fingerprint === fingerprint && statuses.includes(r.status) && r.id !== excludeId && Date.parse(r.updated_at) >= since)
      .sort((a, b) => Date.parse(b.updated_at) - Date.parse(a.updated_at))[0];
    return match ? this.clone(match) : null;
  }

  async listActive(limit: number) {
    return [...this.rows.values()]
      .filter((r) => (r.status === "running" && r.lease_until <= Date.now()) || (r.status === "ready" && r.email && !r.notified_at))
      .slice(0, limit)
      .map((r) => this.clone(r));
  }

  async setEmail(id: string, email: string, leadId: string | null) {
    const row = this.rows.get(id);
    if (!row) return false;
    row.email = email;
    row.lead_id = leadId;
    return true;
  }

  async markNotified(id: string) {
    const row = this.rows.get(id);
    if (!row || row.notified_at) return false;
    row.notified_at = new Date().toISOString();
    return true;
  }
}

const globalStore = globalThis as unknown as { __gcPreviewMemoryStore?: MemoryPreviewStore };

/**
 * The configured store. In production a missing Supabase configuration is a
 * hard stop (null): previews must survive the visitor closing the page.
 */
export function previewStore(): PreviewStore | null {
  const cfg = rpcConfig();
  if (cfg) return new SupabasePreviewStore(cfg);
  if (process.env.NODE_ENV === "production") return null;
  globalStore.__gcPreviewMemoryStore ??= new MemoryPreviewStore();
  return globalStore.__gcPreviewMemoryStore;
}
