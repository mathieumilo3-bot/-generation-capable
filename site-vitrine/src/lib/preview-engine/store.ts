import { randomUUID } from "node:crypto";
import type { Report } from "@/lib/audit-engine/types";
import type { PreviewBlueprint } from "./blueprint-schema";
import type { PipelineState, PreviewWork, StageName } from "./pipeline-types";
import type { VerifiedCompanyProfile } from "./types";

/**
 * Persistence of previews. Production: the `gc_site_previews` table in the
 * audit Supabase project, reached ONLY through SECURITY DEFINER RPCs gated by
 * the same server secret as the audit leads (the table itself has RLS on and
 * no policy). Development/tests: an in-memory store with the same semantics.
 */

export type PreviewStatus = "running" | "needs_input" | "ready" | "failed";

export type PreviewInput = {
  companyName: string;
  cityHint?: string;
  /** Origin the visitor started from (validated), used for the e-mail link. */
  origin?: string;
};

export type PreviewRow = {
  id: string;
  status: PreviewStatus;
  stage: StageName;
  needs: "city" | "site" | null;
  company_name: string;
  siren: string | null;
  official_domain: string | null;
  fingerprint: string | null;
  input: PreviewInput;
  attribution: Record<string, string>;
  pipeline: PipelineState;
  work: PreviewWork;
  company_profile: VerifiedCompanyProfile | null;
  audit_report: Report | null;
  preview_blueprint: PreviewBlueprint | null;
  email: string | null;
  notified_at: string | null;
  lead_id: string | null;
  engine_version: string;
  error_code: string | null;
  created_at: string;
  updated_at: string;
  ready_at: string | null;
  expires_at: string | null;
};

export type PreviewPatch = Partial<
  Pick<
    PreviewRow,
    | "status"
    | "stage"
    | "needs"
    | "company_name"
    | "siren"
    | "official_domain"
    | "fingerprint"
    | "pipeline"
    | "work"
    | "company_profile"
    | "audit_report"
    | "preview_blueprint"
    | "engine_version"
    | "error_code"
    | "ready_at"
    | "expires_at"
  >
>;

export type CreatePreview = {
  /** Generated by the server (UUID v4) so the token hash can be stored at creation. */
  id: string;
  idempotencyKey: string;
  tokenHash: string;
  companyName: string;
  input: PreviewInput;
  attribution: Record<string, string>;
  pipeline: PipelineState;
  work: PreviewWork;
  stage: StageName;
  engineVersion: string;
};

export interface PreviewStore {
  readonly kind: "supabase" | "memory";
  /** Idempotent on `idempotencyKey`: a replay returns the preview already created. */
  create(input: CreatePreview): Promise<PreviewRow | null>;
  get(id: string): Promise<PreviewRow | null>;
  /** Takes the advancing lease if free (or expired). Returns the row either way. */
  claim(id: string, leaseMs: number): Promise<{ row: PreviewRow; leaseId: string | null } | null>;
  /** Writes the patch only while holding the lease, then releases it. */
  save(id: string, leaseId: string, patch: PreviewPatch): Promise<boolean>;
  /** Most recent preview for a fingerprint, among the given statuses, younger than maxAgeHours. */
  findByFingerprint(fingerprint: string, statuses: PreviewStatus[], maxAgeHours: number, excludeId?: string): Promise<PreviewRow | null>;
  /** Previews still running, plus ready ones whose e-mail is still owed — for the background worker. */
  listActive(limit: number): Promise<PreviewRow[]>;
  setEmail(id: string, email: string, leadId: string | null): Promise<boolean>;
  /** True only the first time: guards the ready e-mail against double sends. */
  markNotified(id: string): Promise<boolean>;
}

// ---------------------------------------------------------------------------
// Supabase (RPC)

type RpcConfig = { url: string; key: string; secret: string };

function rpcConfig(): RpcConfig | null {
  const url = process.env.GC_AUDIT_SUPABASE_URL || "";
  const key = process.env.GC_AUDIT_SUPABASE_KEY || "";
  const secret = process.env.GC_AUDIT_RPC_SECRET || "";
  return url && key && secret ? { url, key, secret } : null;
}

async function rpc<T>(cfg: RpcConfig, name: string, args: Record<string, unknown>): Promise<T | null> {
  try {
    const response = await fetch(`${cfg.url}/rest/v1/rpc/${name}`, {
      method: "POST",
      headers: { apikey: cfg.key, Authorization: `Bearer ${cfg.key}`, "Content-Type": "application/json" },
      body: JSON.stringify({ p_secret: cfg.secret, ...args }),
      cache: "no-store",
      signal: AbortSignal.timeout(4_000),
    });
    const text = await response.text();
    if (!response.ok) {
      console.error("[preview/store] RPC failed:", name, response.status, text.slice(0, 300));
      return null;
    }
    return text ? (JSON.parse(text) as T) : null;
  } catch (error) {
    console.error("[preview/store] RPC error:", name, error instanceof Error ? error.name : "unknown");
    return null;
  }
}

function first(rows: PreviewRow[] | PreviewRow | null): PreviewRow | null {
  if (!rows) return null;
  return Array.isArray(rows) ? rows[0] ?? null : rows;
}

export class SupabasePreviewStore implements PreviewStore {
  readonly kind = "supabase" as const;
  constructor(private readonly cfg: RpcConfig) {}

  async create(input: CreatePreview) {
    return first(
      await rpc<PreviewRow[]>(this.cfg, "gc_preview_create", {
        p_id: input.id,
        p_idempotency_key: input.idempotencyKey,
        p_token_hash: input.tokenHash,
        p_company_name: input.companyName,
        p_input: input.input,
        p_attribution: input.attribution,
        p_pipeline: input.pipeline,
        p_work: input.work,
        p_stage: input.stage,
        p_engine_version: input.engineVersion,
      })
    );
  }

  async get(id: string) {
    return first(await rpc<PreviewRow[]>(this.cfg, "gc_preview_get", { p_id: id }));
  }

  async claim(id: string, leaseMs: number) {
    const result = await rpc<{ claimed: boolean; lease_id: string | null; row: PreviewRow | null }>(this.cfg, "gc_preview_claim", {
      p_id: id,
      p_lease_ms: leaseMs,
    });
    if (!result?.row) return null;
    return { row: result.row, leaseId: result.claimed ? result.lease_id : null };
  }

  async save(id: string, leaseId: string, patch: PreviewPatch) {
    return (await rpc<boolean>(this.cfg, "gc_preview_save", { p_id: id, p_lease_id: leaseId, p_patch: patch })) === true;
  }

  async findByFingerprint(fingerprint: string, statuses: PreviewStatus[], maxAgeHours: number, excludeId?: string) {
    return first(
      await rpc<PreviewRow[]>(this.cfg, "gc_preview_find", {
        p_fingerprint: fingerprint,
        p_statuses: statuses,
        p_max_age_hours: maxAgeHours,
        p_exclude_id: excludeId ?? null,
      })
    );
  }

  async listActive(limit: number) {
    return (await rpc<PreviewRow[]>(this.cfg, "gc_preview_list_active", { p_limit: limit })) ?? [];
  }

  async setEmail(id: string, email: string, leadId: string | null) {
    return (await rpc<boolean>(this.cfg, "gc_preview_set_email", { p_id: id, p_email: email, p_lead_id: leadId })) === true;
  }

  async markNotified(id: string) {
    return (await rpc<boolean>(this.cfg, "gc_preview_mark_notified", { p_id: id })) === true;
  }
}

